#!/usr/bin/env python3
"""Batch 6 (D-02): cut each wide painted scene into 1200 px strips, LOSSLESSLY.

The shipped paintings in assets/art/scene/*.webp are not changed or repainted. Each strip is the
exact decoded pixels of the original (lossless WebP), so the painting looks the same; only the
strips that are on screen get fetched and decoded, instead of one 18-35 MB bitmap per scene.
Writes assets/art/scene-tiles/<scene>/<scene>.<i>.webp and src/art/scene-tiles.ts, then
verifies every strip is pixel-identical to the matching crop of the original.
usage: python3 scripts/tile_scenes.py [--check]   (--check: verify only, write nothing)
"""
import json, sys
from pathlib import Path
from PIL import Image, ImageChops
ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'assets' / 'art' / 'scene'
OUT = ROOT / 'assets' / 'art' / 'scene-tiles'
MAN = ROOT / 'src' / 'art' / 'scene-tiles.ts'
TILE = 1200
SKIP = {'map', 'map-portrait'}  # fit-to-screen cards: always fully visible, nothing to gain
check_only = '--check' in sys.argv
man = {}; bad = 0
for f in sorted(SRC.glob('*.webp')):
    name = f.stem
    if name in SKIP or name.startswith('_'): continue
    im = Image.open(f).convert('RGB'); W, H = im.size
    if W <= TILE * 2: continue
    tiles = []
    for i, x in enumerate(range(0, W, TILE)):
        w = min(TILE, W - x); crop = im.crop((x, 0, x + w, H))
        p = OUT / name / f'{name}.{i}.webp'
        if not check_only:
            p.parent.mkdir(parents=True, exist_ok=True)
            crop.save(p, 'WEBP', lossless=True, method=6, quality=100, exact=True)
        got = Image.open(p).convert('RGB')
        same = got.size == crop.size and ImageChops.difference(got, crop).getbbox() is None
        if not same: bad += 1; print('NOT IDENTICAL', p)
        tiles.append([x, w])
    man[name] = {'w': W, 'h': H, 'tiles': tiles}
    print(f'{name}: {W}x{H} -> {len(tiles)} strips, pixel-identical')
HEAD = '// Generated by scripts/tile_scenes.py - do not edit. Scene -> painting size and its [x, width] strips (2x px).\n'
body = HEAD + 'export const TILE_MAN: Record<string, { w: number; h: number; tiles: [number, number][] }> = ' + json.dumps(man) + ';\n'
if not check_only: MAN.write_text(body)
elif not MAN.exists() or MAN.read_text() != body: bad += 1; print('manifest out of date')
print('TILES', 'OK' if not bad else f'{bad} BAD'); sys.exit(1 if bad else 0)
